-- 1. HR_EMPLOYEES
CREATE TABLE HR_EMPLOYEES (
    EMPLOYEE_ID       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    EMPLOYEE_NUMBER   VARCHAR2(20)  NOT NULL CONSTRAINT UK_HR_EMP_NUM UNIQUE,
    FIRST_NAME        VARCHAR2(50)  NOT NULL,
    LAST_NAME         VARCHAR2(50)  NOT NULL,
    EMAIL             VARCHAR2(100),
    PHONE_NUMBER      VARCHAR2(20),
    DATE_OF_BIRTH     DATE,
    HIRE_DATE         DATE          NOT NULL,
    GENDER            VARCHAR2(10),
    EMPLOYMENT_STATUS VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT        TIMESTAMP     DEFAULT SYSTIMESTAMP
);

-- 2. HR_DEPARTMENTS
CREATE TABLE HR_DEPARTMENTS (
    DEPARTMENT_ID     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    DEPARTMENT_NAME   VARCHAR2(100) NOT NULL
);

-- 3. HR_JOBS
CREATE TABLE HR_JOBS (
    JOB_ID            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    JOB_TITLE         VARCHAR2(100) NOT NULL
);

-- 4. HR_ASSIGNMENTS
CREATE TABLE HR_ASSIGNMENTS (
    ASSIGNMENT_ID     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    EMPLOYEE_ID       NUMBER        NOT NULL CONSTRAINT FK_ASG_EMP  REFERENCES HR_EMPLOYEES(EMPLOYEE_ID) ON DELETE CASCADE,
    DEPARTMENT_ID     NUMBER        NOT NULL CONSTRAINT FK_ASG_DEPT REFERENCES HR_DEPARTMENTS(DEPARTMENT_ID),
    JOB_ID            NUMBER        NOT NULL CONSTRAINT FK_ASG_JOB  REFERENCES HR_JOBS(JOB_ID),
    MANAGER_ID        NUMBER        CONSTRAINT FK_ASG_MGR  REFERENCES HR_EMPLOYEES(EMPLOYEE_ID),
    START_DATE        DATE          NOT NULL,
    END_DATE          DATE,
    ASSIGNMENT_STATUS VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL,
    SALARY            NUMBER(12,2)  NOT NULL
);

-- 5. HR_ABSENCE_TYPES
CREATE TABLE HR_ABSENCE_TYPES (
    ABSENCE_TYPE_ID   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ABSENCE_TYPE_NAME VARCHAR2(100) NOT NULL
);

-- 6. HR_ABSENCE_REQUESTS
CREATE TABLE HR_ABSENCE_REQUESTS (
    REQUEST_ID        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    EMPLOYEE_ID       NUMBER        NOT NULL CONSTRAINT FK_ABS_EMP  REFERENCES HR_EMPLOYEES(EMPLOYEE_ID) ON DELETE CASCADE,
    ABSENCE_TYPE_ID   NUMBER        NOT NULL CONSTRAINT FK_ABS_TYPE REFERENCES HR_ABSENCE_TYPES(ABSENCE_TYPE_ID),
    START_DATE        DATE          NOT NULL,
    END_DATE          DATE          NOT NULL,
    DAYS_REQUESTED    NUMBER(5,1),
    REASON            VARCHAR2(500),
    REQUEST_STATUS    VARCHAR2(20)  DEFAULT 'PENDING',
    APPROVED_BY       NUMBER        CONSTRAINT FK_ABS_APPR REFERENCES HR_EMPLOYEES(EMPLOYEE_ID),
    APPROVAL_DATE     DATE,
    CREATED_AT        DATE          DEFAULT SYSDATE
);

-- 7. HR_APPROVAL_HISTORY
CREATE TABLE HR_APPROVAL_HISTORY (
    HISTORY_ID        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    REQUEST_ID        NUMBER        NOT NULL CONSTRAINT FK_HIST_REQ  REFERENCES HR_ABSENCE_REQUESTS(REQUEST_ID) ON DELETE CASCADE,
    PROCESSED_BY      NUMBER        NOT NULL CONSTRAINT FK_HIST_EMP  REFERENCES HR_EMPLOYEES(EMPLOYEE_ID),
    DECISION          VARCHAR2(20)  NOT NULL,
    PROCESSED_AT      DATE          DEFAULT SYSDATE,
    COMMENTS          VARCHAR2(500)
);

-- 8. HR_PAYROLL
CREATE TABLE HR_PAYROLL (
    PAYROLL_ID        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    EMPLOYEE_ID       NUMBER        NOT NULL CONSTRAINT FK_PAY_EMP REFERENCES HR_EMPLOYEES(EMPLOYEE_ID) ON DELETE CASCADE,
    PAY_PERIOD_MONTH  NUMBER(2)     NOT NULL,
    PAY_PERIOD_YEAR   NUMBER(4)     NOT NULL,
    BASIC_SALARY      NUMBER(12,2)  NOT NULL,
    ALLOWANCES        NUMBER(12,2)  DEFAULT 0,
    DEDUCTIONS        NUMBER(12,2)  DEFAULT 0,
    GROSS_SALARY      NUMBER(12,2),
    NET_SALARY        NUMBER(12,2),
    PAYROLL_STATUS    VARCHAR2(20)  DEFAULT 'PENDING',
    CREATED_AT        DATE          DEFAULT SYSDATE
);

-- ============================================================================
-- STORED PROCEDURES REQUIRED BY PAGES 10 & 16
-- ============================================================================

-- Procedure 1: PROCESS_LEAVE_REQUEST (Called on Page 10)
CREATE OR REPLACE PROCEDURE PROCESS_LEAVE_REQUEST (
    p_request_id  IN NUMBER,
    p_approver_id IN NUMBER,
    p_decision    IN VARCHAR2,
    p_comments    IN VARCHAR2
) AS
BEGIN
    IF p_request_id IS NULL THEN
        RAISE_APPLICATION_ERROR(-20010, 'Leave Request ID is required.');
    END IF;

    UPDATE HR_ABSENCE_REQUESTS
       SET REQUEST_STATUS = p_decision,
           APPROVED_BY    = p_approver_id,
           APPROVAL_DATE  = SYSDATE
     WHERE REQUEST_ID     = p_request_id;

    INSERT INTO HR_APPROVAL_HISTORY (
        REQUEST_ID,
        PROCESSED_BY,
        DECISION,
        PROCESSED_AT,
        COMMENTS
    ) VALUES (
        p_request_id,
        p_approver_id,
        p_decision,
        SYSDATE,
        p_comments
    );
END PROCESS_LEAVE_REQUEST;
/

-- Procedure 2: PROCESS_PAYROLL (Called on Page 16)
CREATE OR REPLACE PROCEDURE PROCESS_PAYROLL (
    p_payroll_id IN NUMBER
) AS
BEGIN
    UPDATE HR_PAYROLL
       SET GROSS_SALARY   = NVL(BASIC_SALARY, 0) + NVL(ALLOWANCES, 0),
           NET_SALARY     = NVL(BASIC_SALARY, 0) + NVL(ALLOWANCES, 0) - NVL(DEDUCTIONS, 0),
           PAYROLL_STATUS = 'PROCESSED'
     WHERE PAYROLL_ID     = p_payroll_id;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20032, 'Payroll record not found.');
    END IF;
END PROCESS_PAYROLL;
/

-- Procedure 3: MARK_PAYROLL_PAID (Called on Page 16)
CREATE OR REPLACE PROCEDURE MARK_PAYROLL_PAID (
    p_payroll_id IN NUMBER
) AS
BEGIN
    UPDATE HR_PAYROLL
       SET GROSS_SALARY   = NVL(GROSS_SALARY, NVL(BASIC_SALARY, 0) + NVL(ALLOWANCES, 0)),
           NET_SALARY     = NVL(NET_SALARY, NVL(BASIC_SALARY, 0) + NVL(ALLOWANCES, 0) - NVL(DEDUCTIONS, 0)),
           PAYROLL_STATUS = 'PAID'
     WHERE PAYROLL_ID     = p_payroll_id;

    IF SQL%ROWCOUNT = 0 THEN
        RAISE_APPLICATION_ERROR(-20042, 'Payroll record not found.');
    END IF;
END MARK_PAYROLL_PAID;
/

